"""Stage: keyframes. One still image per shot from Cloudflare Workers AI (FLUX).

    python -m pipeline.keyframes
    python -m pipeline.keyframes --shots s04 s05
    python -m pipeline.keyframes --offline     # flat colour placeholders, no API

The prompt for each shot is built the same way every time, which is what keeps the look consistent:
    style.visual_prefix + character descriptions (verbatim) + shot.keyframe_prompt + camera
Output: outputs/keyframes/<shot>_<hash>.jpg and manifest.json
"""
from __future__ import annotations

import argparse
import base64
import json
import os

from .common import rel, from_manifest, OUTPUTS, shots_blocked_by_consent, cache_key, load_env, load_storyboard, log_call, run_ffmpeg, select_shots, stage_dir, with_retries, write_manifest

STAGE = "keyframes"
CF_MODEL = os.environ.get("CF_IMAGE_MODEL", "@cf/black-forest-labs/flux-1-schnell")


def build_prompt(sb: dict, shot: dict) -> str:
    chars = {c["id"]: c["description"] for c in sb.get("characters", [])}
    parts = [sb["style"]["visual_prefix"]]
    # Character descriptions are repeated verbatim in every shot: the cheapest consistency trick there is.
    # Always in storyboard order, so a person's description sits in the same place in every prompt.
    in_shot = set(shot.get("characters", []))
    parts += [f"The {c} is {d}." for c, d in chars.items() if c in in_shot]
    parts.append(shot["keyframe_prompt"])
    if shot.get("camera"):
        parts.append(f"Shot: {shot['camera']}.")
    if sb["style"].get("negative"):
        parts.append(f"No {sb['style']['negative']}.")
    return " ".join(parts)


def cf_generate(prompt: str, seed: int, steps: int = 8) -> bytes:
    import requests

    acct, token = os.environ["CLOUDFLARE_ACCOUNT_ID"], os.environ["CLOUDFLARE_API_TOKEN"]
    url = f"https://api.cloudflare.com/client/v4/accounts/{acct}/ai/run/{CF_MODEL}"
    payload = {"prompt": prompt[:2048], "steps": steps}
    # flux-1-schnell's schema rejects "seed" (400, code 5006: unevaluated property '/seed'), so its
    # output isn't seed-reproducible; the seed still goes into the cache key and runs.jsonl.
    if "flux-1-schnell" not in CF_MODEL:
        payload["seed"] = seed
    r = requests.post(url, headers={"Authorization": f"Bearer {token}"}, json=payload, timeout=120)
    if r.status_code == 429:
        from .common import QuotaError
        raise QuotaError(r.text[:300])
    r.raise_for_status()
    body = r.json()
    img = (body.get("result") or {}).get("image")
    if not img:
        raise RuntimeError(f"No image in response: {str(body)[:300]}")
    return base64.b64decode(img)


_chain = None


def get_chain():
    """Gemini client, opened only when something actually has to be generated (cached runs need no API)."""
    global _chain
    if _chain is None:
        from .gemini_images import ImageChain
        _chain = ImageChain()
    return _chain


def gemini_shot(sb: dict, shot: dict, prompt: str, seed: int, out_dir, force: bool, prev: dict) -> dict:
    """A shot with real people, generated by Gemini from each person's reference portrait (pipeline/gemini_images.py)."""
    from . import gemini_images as gi

    real = {c["id"] for c in sb["characters"] if c.get("real_person")}
    people = [c["id"] for c in sb["characters"] if c["id"] in set(shot.get("characters", [])) & real]
    sid = shot["id"]
    refs = gi.ensure_refs(sb, people, get_chain)
    ref_keys = [r.stem for r in refs.values()]
    key = cache_key(STAGE, "gemini", prompt, seed, ref_keys)
    out = out_dir / f"{sid}_{key}.png"
    contents, instruction = gi.shot_contents(prompt, people, refs)
    params = {"prompt": instruction, "refs": [rel(r) for r in refs.values()]}
    if out.exists() and not force:
        model = prev.get("model") if prev.get("file") == rel(out) else None
        log_call(stage=STAGE, provider="gemini", model=model or "?", shot=sid, seed=seed, params=params, cache_hit=True, output=out)
        print(f"  = {sid} cached (gemini)")
    else:
        data, model = get_chain().generate(contents, shot=sid, params=params, out=out)
        out.write_bytes(data)
        print(f"  + {sid} ({model}, refs: {', '.join(people)})")
    entry = {"file": rel(out), "prompt": instruction, "seed": seed, "provider": "gemini", "refs": params["refs"]}
    if model:
        entry["model"] = model
    return entry


def main(argv=None) -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--shots", nargs="*")
    ap.add_argument("--offline", action="store_true")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--steps", type=int, default=8)
    args = ap.parse_args(argv)

    load_env()
    sb = load_storyboard()
    if not args.offline and not (os.environ.get("CLOUDFLARE_ACCOUNT_ID") and os.environ.get("CLOUDFLARE_API_TOKEN")):
        raise SystemExit("CLOUDFLARE_ACCOUNT_ID / CLOUDFLARE_API_TOKEN not set (see README), or pass --offline.")
    provider, model = ("offline", "placeholder") if args.offline else ("cloudflare", CF_MODEL)
    out_dir = stage_dir(STAGE)
    mpath = OUTPUTS / STAGE / "manifest.json"
    manifest = json.loads(mpath.read_text(encoding="utf-8")) if mpath.exists() else {}

    shots = select_shots(sb, args.shots)
    blocked = shots_blocked_by_consent(sb, shots)
    for sid, refs in blocked.items():
        print(f"  x {sid} skipped: no recorded consent for {', '.join(refs)} (see ETHICS.md)")
    for i, shot in enumerate(shots):
        if shot["id"] in blocked:
            continue
        sid, seed = shot["id"], shot.get("seed", 0)
        prompt = build_prompt(sb, shot)
        if shot.get("image_provider") == "gemini" and not args.offline:
            try:
                manifest[sid] = gemini_shot(sb, shot, prompt, seed, out_dir, args.force, manifest.get(sid, {}))
            except SystemExit as e:  # no Gemini image model usable: keep this shot's previous still, carry on
                print(f"  x {sid} not regenerated, previous still kept: {e}")
            continue
        params = {"steps": args.steps, "prompt": prompt}
        key = cache_key(STAGE, provider, model, prompt, seed, args.steps)
        out = out_dir / f"{sid}_{key}.jpg"
        if out.exists() and not args.force:
            log_call(stage=STAGE, provider=provider, model=model, shot=sid, seed=seed, params=params, cache_hit=True, output=out)
            print(f"  = {sid} cached")
        elif args.offline:
            hue = (i * 37) % 360
            run_ffmpeg(["-f", "lavfi", "-i", f"color=c=0x{(hue*7)%256:02x}{(hue*3)%256:02x}{(hue*5)%256:02x}:s=1024x1024", "-frames:v", "1", str(out)])
            log_call(stage=STAGE, provider=provider, model=model, shot=sid, seed=seed, params=params, output=out)
            print(f"  + {sid} placeholder")
        else:
            img = with_retries(lambda att: cf_generate(prompt, seed, args.steps), stage=STAGE, provider=provider,
                               model=model, shot=sid, seed=seed, params=params, output=out)
            out.write_bytes(img)
            print(f"  + {sid}")
        manifest[sid] = {"file": rel(out), "prompt": prompt, "seed": seed}
    write_manifest(STAGE, manifest)


if __name__ == "__main__":
    main()
